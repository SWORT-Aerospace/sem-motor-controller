#!/usr/bin/env python3
"""Bench package: everything a bench session needs, in one folder with checksums.

    python3 tools/bench_package.py --doc               # write hardware/acceptance/BENCH_PACKAGE.md
    python3 tools/bench_package.py --doc --check       # fail if that page is stale
    python3 tools/bench_package.py --images build-g4 --board BOARD-01 --out build/bench_package

The page (committed) lists the firmware images and which acceptance stages use each, the connector pin tables
taken from the KiCad netlist, the equipment per stage, and the checks behind the claim that the PWM bench image
cannot drive a gate. The package (built, not committed; CI uploads it) adds the images with their SHA-256 and
revision strings, the schematic PDF, the procedures, one result template per stage for the named board, the
bench scripts, the consistency report and a MANIFEST.json with the SHA-256 of every file.

It contains no calibration: none is hardware-valid yet (release gate G7), and the firmware refuses a synthetic
one. Nothing here flashes, powers or tests anything.
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from tools import acceptance  # noqa: E402
from tools import hw_consistency as HC  # noqa: E402

DOC = ROOT / "hardware" / "acceptance" / "BENCH_PACKAGE.md"
IMAGES = [
    ("semmc_stm32g474", "operational",
     "The controller image: start-up sequence, protection, CAN, bench readout (g_bench). Drives nothing until both "
     "device descriptions are verified, GATE_DRIVER_CONFIGURED is set and a hardware-valid calibration is loaded."),
    ("semmc_stm32g474_pwmtest", "PWM bench",
     "Acceptance stage 4 only: TIM1 switches its six outputs at fixed duties with DRV_ENABLE held low. Never load "
     "it on a board whose bridge is powered (precharge resistor fitted or the bypass able to close)."),
    ("semmc_stm32g474_timing", "timing marker",
     "The operational image with the status-LED pin (PE14) high during the fast interrupt, for the scope "
     "measurements of stage 7; the LED does not blink."),
]
NAME_PREFIX = "semmc stm32g474 "


def stages_using(image: str) -> list[str]:
    """Energised stages whose text names the image (the PWM and timing images by name; the operational one by
    'controller image')."""
    proc = acceptance.load_procedures()
    out = []
    for s in proc["stages"]:
        if not s.get("energised"):
            continue  # S0 and S1 build or inspect; no image runs there
        text = json.dumps(s)
        if image == "semmc_stm32g474_pwmtest" and "pwmtest" in text:
            out.append(s["id"])
        elif image == "semmc_stm32g474_timing" and "semmc_stm32g474_timing" in text:
            out.append(s["id"])
        elif image == "semmc_stm32g474" and re.search(r"controller image", text):
            out.append(s["id"])
    return out


def connector_tables() -> list[str]:
    comps, nets, pin_net = HC.parse_netlist(HC.NET)
    L = []
    for ref in sorted((r for r in comps if r.startswith("J")), key=lambda r: int(re.sub(r"\D", "", r))):
        pins = sorted(((p, n) for (r, p), n in pin_net.items() if r == ref), key=lambda x: int(x[0]) if x[0].isdigit() else 0)
        L += [f"**{ref}** ({comps[ref]['value']}, {comps[ref]['lib']}:{comps[ref]['part']})", "",
              "| Pin | Net |", "|---|---|"] + [f"| {p} | `{n}` |" for p, n in pins] + [""]
    return L


def gate_checks() -> list[tuple[str, str, str]]:
    return [r for r in HC.run() if r[0].startswith(("BP", "PR1", "PR2", "PR3"))]


def render_doc() -> str:
    proc = acceptance.load_procedures()
    L = ["# Bench package", "",
         "Generated by `tools/bench_package.py --doc` from `hardware/acceptance/procedures.yaml`, the KiCad netlist and "
         "the consistency checks; do not edit. Build the package itself with "
         "`python3 tools/bench_package.py --images build-g4 --board <serial> --out build/bench_package` after building "
         "the images (`firmware/platform/stm32g4/FLASHING.md`, step 1); CI builds it on every push (artifact "
         "`bench-package`, board `UNASSIGNED`).", "",
         "The procedure, limits and stop conditions are [`docs/BENCH_ACCEPTANCE.md`](../../docs/BENCH_ACCEPTANCE.md); "
         "this page lists what goes to the bench with them. No calibration is included: none is hardware-valid yet.", "",
         "## Firmware images", "", "| Image | Role | Stages | What it does |", "|---|---|---|---|"]
    for name, role, what in IMAGES:
        L.append(f"| `{name}.elf` | {role} | {', '.join(stages_using(name)) or '-'} | {what} |")
    L += ["", "Each image prints `" + NAME_PREFIX + "...` and its revision on the UART at reset; the PWM bench image "
          "says `BENCH PWM TEST` and the timing image `TIMING MARKER`. A revision ending in `-modified` is not "
          "acceptable for a recorded test. The package's `MANIFEST.json` holds each image's SHA-256.", "",
          "## Why the PWM bench image cannot drive a gate", "",
          "Stage 4 switches the six gate-signal pins. What keeps the MOSFET gates off, and how each part is "
          "established (netlist checks of `tools/hw_consistency.py`):", "",
          "| Check | Result | Detail |", "|---|---|---|"]
    for cid, status, detail in gate_checks():
        L.append(f"| {cid} | {status} | {detail.replace('|', '/')} |")
    L += ["", "So the stage 4 protection rests on circuit facts (the PWM pins reach only the driver; the gates reach "
          "only the driver; with the precharge resistor unfitted nothing supplies the driver; ENABLE has pull-downs "
          "and the AND gate) and on the firmware never raising DRV_ENABLE. What the driver itself does with ENABLE low "
          "or without supply is not established until its data sheet is read (BP5); stage 4 therefore measures every "
          "gate at 0 V before and while the image runs, and stops on any gate voltage.", "",
          "## Equipment by stage", "", "| Stage | Energised | Equipment |", "|---|---|---|"]
    for s in proc["stages"]:
        eq = "; ".join(s.get("equipment", [])) or "-"
        L.append(f"| {s['id']} {s['title']} | {'yes' if s.get('energised') else 'no'} | {eq} |")
    L += ["", "## Connector pin tables (from the netlist)", "",
          "The connector families wait for the harness (B-HARNESS); the pin assignments below are the schematic's.", ""]
    L += connector_tables()
    L += ["## Package contents", "",
          "| Folder | Contents |", "|---|---|",
          "| `images/` | the three images (`.elf`, `.bin`, `.hex`) |",
          "| `procedures/` | `BENCH_ACCEPTANCE.md`, `procedures.yaml`, `FLASHING.md` |",
          "| `templates/` | one result record per stage for the board (`tools/acceptance.py template`) |",
          "| `scripts/` | `bench_read.py`, `acceptance.py` and this repository's `requirements.txt` |",
          "| `drawings/` | the schematic PDF; no board drawing exists (no PCB) |",
          "| `checks/` | `CONSISTENCY_CHECK.md`, `FOOTPRINT_CHECK.md`, the release gate result |",
          "| `pins/` | the MCU pin allocation and this page's connector tables |",
          "| `MANIFEST.json` | commit, build state, the SHA-256 of every file and the image revision strings |", ""]
    return "\n".join(L)


def sha256(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def image_revision(elf: pathlib.Path) -> str:
    data = elf.read_bytes()
    m = re.search(rb"semmc stm32g474 [ -~]{1,80}", data)
    return m.group(0).decode() if m else "unknown"


def build(images: pathlib.Path, board: str, out: pathlib.Path) -> int:
    missing = [n for n, _r, _w in IMAGES if not (images / f"{n}.elf").exists()]
    if missing:
        print(f"images not built in {images}: {missing}", file=sys.stderr)
        return 1
    if out.exists():
        shutil.rmtree(out)
    for sub in ("images", "procedures", "templates", "scripts", "drawings", "checks", "pins"):
        (out / sub).mkdir(parents=True)
    revs = {}
    for name, _r, _w in IMAGES:
        for ext in (".elf", ".bin", ".hex"):
            src = images / f"{name}{ext}"
            if src.exists():
                shutil.copy2(src, out / "images" / src.name)
        revs[name] = image_revision(images / f"{name}.elf")
    copies = {"procedures": ["docs/BENCH_ACCEPTANCE.md", "hardware/acceptance/procedures.yaml",
                             "firmware/platform/stm32g4/FLASHING.md"],
              "scripts": ["tools/bench_read.py", "tools/acceptance.py", "requirements.txt"],
              "drawings": ["hardware/kicad/semmc_schematic_DRAFT.pdf"],
              "checks": ["hardware/review/CONSISTENCY_CHECK.md", "hardware/footprints/FOOTPRINT_CHECK.md",
                         "docs/generated/release_gate.md"],
              "pins": ["hardware/interfaces/pin_allocation_STM32G474VBCETx.csv", "hardware/acceptance/BENCH_PACKAGE.md"]}
    for sub, files in copies.items():
        for f in files:
            shutil.copy2(ROOT / f, out / sub / pathlib.Path(f).name)
    proc = acceptance.load_procedures()
    for s in proc["stages"]:
        rec = acceptance.template(proc, s["id"], board)
        (out / "templates" / f"{s['id']}_{board}.json").write_text(json.dumps(rec, indent=2) + "\n")
    git = lambda *a: subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True).stdout.strip()  # noqa: E731
    files = {str(p.relative_to(out)): sha256(p) for p in sorted(out.rglob("*")) if p.is_file()}
    manifest = {"commit": git("rev-parse", "HEAD"), "tree_modified": bool(git("status", "--porcelain", "--untracked-files=no")),
                "built": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"), "board": board,
                "image_revisions": revs, "calibration": "none: no hardware-valid calibration exists (release gate G7)",
                "files": files}
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {out}: {len(files)} files, commit {manifest['commit'][:12]}"
          + (" (tree modified: not acceptable for a recorded test)" if manifest["tree_modified"] else ""))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--doc", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--images", type=pathlib.Path)
    ap.add_argument("--board", default="UNASSIGNED")
    ap.add_argument("--out", type=pathlib.Path, default=ROOT / "build" / "bench_package")
    a = ap.parse_args()
    if a.doc:
        text = render_doc()
        if a.check:
            if not DOC.exists() or DOC.read_text() != text:
                print(f"{DOC.relative_to(ROOT)} is stale: run python3 tools/bench_package.py --doc", file=sys.stderr)
                return 1
            return 0
        DOC.write_text(text)
        print(f"wrote {DOC.relative_to(ROOT)}")
        return 0
    if a.images is None:
        ap.error("--images DIR (the target build directory) or --doc")
    return build(a.images, a.board, a.out)


if __name__ == "__main__":
    sys.exit(main())
