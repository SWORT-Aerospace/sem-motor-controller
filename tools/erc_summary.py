#!/usr/bin/env python3
"""Summarise a KiCad ERC JSON report (kicad-cli sch erc --format json).

    python3 tools/erc_summary.py hardware/kicad/ERC_REPORT.json [--fail-on-errors] [--md OUT.md]

Prints the counts by severity and by violation type, and every error with the
items it names. With --fail-on-errors the exit code is 1 when the report has
any error. Warnings are listed, never dropped.
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import sys


def load(path: pathlib.Path) -> tuple[str, list[dict]]:
    rep = json.loads(path.read_text())
    out = []
    for sheet in rep.get("sheets", []):
        for v in sheet.get("violations", []):
            out.append({"sheet": sheet.get("path", "?"), "severity": v.get("severity", "?"),
                        "type": v.get("type", "?"), "description": v.get("description", ""),
                        "items": [i.get("description", "") for i in v.get("items", [])]})
    return rep.get("kicad_version", "?"), out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("report", type=pathlib.Path)
    ap.add_argument("--fail-on-errors", action="store_true")
    ap.add_argument("--md", type=pathlib.Path)
    a = ap.parse_args()
    ver, vs = load(a.report)
    sev = collections.Counter(v["severity"] for v in vs)
    typ = collections.Counter((v["severity"], v["type"]) for v in vs)
    L = [f"KiCad ERC ({ver}): {sev.get('error', 0)} errors, {sev.get('warning', 0)} warnings, "
         f"{sum(sev.values())} violations in total", ""]
    L += [f"  {s:8s} {t:40s} {n}" for (s, t), n in sorted(typ.items())]
    L.append("")
    for v in vs:
        if v["severity"] == "error":
            L.append(f"ERROR {v['type']} on {v['sheet']}: {v['description']} | " + " ; ".join(v["items"]))
    print("\n".join(L))
    if a.md:
        md = ["# KiCad ERC summary", "", f"KiCad {ver}. Generated by `tools/erc_summary.py` from the ERC JSON report.",
              "", "| severity | type | count |", "|---|---|---|"]
        md += [f"| {s} | {t} | {n} |" for (s, t), n in sorted(typ.items())]
        md += ["", "## Violations", ""]
        md += [f"* **{v['severity']}** `{v['type']}` ({v['sheet']}): {v['description']} - {'; '.join(v['items'])}"
               for v in vs]
        a.md.write_text("\n".join(md) + "\n")
    return 1 if a.fail_on_errors and sev.get("error", 0) else 0


if __name__ == "__main__":
    sys.exit(main())
