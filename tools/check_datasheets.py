#!/usr/bin/env python3
"""Primary-document manifest: render the download list and record what has been received.

    python3 tools/check_datasheets.py            # write docs/reference/datasheets/README.md
    python3 tools/check_datasheets.py --record   # add SHA-256 and size of PDFs present in the folder
    python3 tools/check_datasheets.py --check    # fail if the README is stale or a received file changed

Source: docs/reference/datasheets/manifest.yaml. A document is "received" only when its file is in the folder,
its SHA-256 and size are recorded, and a reviewer has typed the revision and date printed on its cover; the
tool never guesses a revision. A file whose hash no longer matches the record fails the check, so a document
that a design decision cites cannot change silently.
"""
from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIR = ROOT / "docs" / "reference" / "datasheets"
SRC = DIR / "manifest.yaml"
DOC = DIR / "README.md"


def sha256(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def status(d: dict) -> str:
    r = d.get("received") or {}
    if not d.get("file"):
        return "after selection"
    if not (DIR / d["file"]).exists():
        return "missing"
    if r.get("sha256") and r.get("revision") and r.get("date"):
        return "received"
    return "file present, revision not recorded"


def render(data: dict) -> str:
    docs = sorted(data["documents"], key=lambda d: (d["priority"], d["id"]))
    L = ["# Primary documents", "",
         "Generated by `tools/check_datasheets.py` from `manifest.yaml` in this folder; edit the manifest, not this "
         "page.", "",
         "The design cannot be finished without these documents, and the build environment cannot download them: "
         "the manufacturers' sites are refused by its network policy. Either put the PDFs in this folder, or have "
         "the environment owner allow the manufacturers' hosts (cloud environment settings, Network access). Then "
         "run `python3 tools/check_datasheets.py --record`, type each document's revision and date into "
         "`manifest.yaml` from its cover, and commit both. Secondary sources (KiCad symbols, ST's pin database and "
         "HAL headers) are used meanwhile only where the design notes say so; they do not replace these "
         "documents.", "",
         f"Received: {sum(status(d) == 'received' for d in docs)} of "
         f"{sum(bool(d.get('file')) for d in docs)} documents.", "",
         "| # | Document | Part (exact variant) | Manufacturer | File to add | Official page | Status | Unlocks |",
         "|---|---|---|---|---|---|---|---|"]
    for d in docs:
        r = d.get("received") or {}
        st = status(d)
        if st == "received":
            st = f"received: {r['revision']}, {r['date']}, SHA-256 `{r['sha256'][:16]}`"
        url = d.get("official_url") or "n/a"
        url_cell = "n/a" if url == "n/a" else f"{url} (unverified)"
        L.append(f"| {d['priority']} | {d['document']} | {d['part']} | {d['manufacturer']} | "
                 f"{'`' + d['file'] + '`' if d.get('file') else '-'} | {url_cell} | {st} | "
                 f"{' '.join(d['unlocks'].split())} |")
    return "\n".join(L) + "\n"


def record(data: dict) -> list[str]:
    msgs = []
    for d in data["documents"]:
        if not d.get("file"):
            continue
        p = DIR / d["file"]
        if not p.exists():
            continue
        r = d.get("received") or {}
        h = sha256(p)
        if r.get("sha256") and r["sha256"] != h:
            msgs.append(f"{d['id']}: {d['file']} changed (recorded {r['sha256'][:16]}, now {h[:16]}); "
                        "check the revision before replacing the record")
            continue
        r.update(sha256=h, bytes=p.stat().st_size)
        r.setdefault("revision", None)
        r.setdefault("date", None)
        d["received"] = r
        msgs.append(f"{d['id']}: recorded {h[:16]}; type the revision and date from the cover")
    return msgs


def check(data: dict) -> list[str]:
    err = []
    for d in data["documents"]:
        r = d.get("received") or {}
        if r.get("sha256"):
            p = DIR / d["file"]
            if not p.exists():
                err.append(f"{d['id']}: recorded as received but {d['file']} is missing")
            elif sha256(p) != r["sha256"]:
                err.append(f"{d['id']}: {d['file']} does not match its recorded SHA-256")
    if not DOC.exists() or DOC.read_text() != render(data):
        err.append(f"{DOC.relative_to(ROOT)} is out of date (run tools/check_datasheets.py)")
    return err


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true")
    g.add_argument("--record", action="store_true")
    a = ap.parse_args()
    data = yaml.safe_load(SRC.read_text())
    if a.check:
        err = check(data)
        for e in err:
            print(e)
        return 1 if err else 0
    if a.record:
        for m in record(data):
            print(m)
        text = SRC.read_text()
        head = text[:text.index("schema:")]
        SRC.write_text(head + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=120))
    DOC.write_text(render(data))
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
