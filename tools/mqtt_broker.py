"""Start, kill and restart a local Mosquitto broker for host tests and demonstrations.

The broker binary is found from $SEMMC_MOSQUITTO, then `mosquitto` on PATH,
then /usr/sbin/mosquitto (Ubuntu's package). Setup: docs/MQTT_SETUP.md.

The configuration (written next to the persistence files) listens on
127.0.0.1 only, on a free port chosen at start, allows anonymous clients
(local test broker, never exposed), and saves its persistence database after
every change (subscriptions, queued messages), so that a subscriber's session
and the messages queued for it survive a killed broker. A message the broker
acknowledged but had not saved when it was killed can still be lost; the
car-side sequence numbers make such a loss visible.
"""
from __future__ import annotations

import os
import pathlib
import shutil
import signal
import socket
import subprocess
import time

CONF = """# generated by tools/mqtt_broker.py: local host-test broker, loopback only
listener {port} 127.0.0.1
allow_anonymous true
persistence true
persistence_location {dir}/
autosave_interval 1
autosave_on_changes true
max_queued_messages 1000
log_dest file {dir}/mosquitto.log
log_type error
log_type warning
log_type notice
log_type information
connection_messages true
"""


def find_mosquitto() -> str | None:
    for cand in (os.environ.get("SEMMC_MOSQUITTO"), shutil.which("mosquitto"), "/usr/sbin/mosquitto"):
        if cand and os.path.isfile(cand) and os.access(cand, os.X_OK):
            return cand
    return None


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def version(binary: str) -> str:
    out = subprocess.run([binary, "-h"], capture_output=True, text=True, timeout=10)
    first = (out.stdout or out.stderr).strip().splitlines()
    return first[0] if first else "unknown"


class Mosquitto:
    def __init__(self, workdir: pathlib.Path, binary: str | None = None, port: int | None = None):
        self.binary = binary or find_mosquitto()
        if not self.binary:
            raise FileNotFoundError("no mosquitto broker found: set SEMMC_MOSQUITTO or install it (docs/MQTT_SETUP.md)")
        self.dir = pathlib.Path(workdir).resolve()
        self.dir.mkdir(parents=True, exist_ok=True)
        self.port = port or free_port()
        self.conf = self.dir / "mosquitto.conf"
        conf = CONF.format(port=self.port, dir=self.dir)
        if hasattr(os, "geteuid") and os.geteuid() == 0:
            # started as root, Mosquitto would switch to the `mosquitto` user and could not write its
            # persistence and log files in this root-owned directory: keep the starting user
            conf += "user root\n"
        self.conf.write_text(conf)
        self.proc: subprocess.Popen | None = None
        self.events: list[tuple[float, str]] = []          # (monotonic s, "start" | "kill" | "stop")

    def start(self, timeout_s: float = 10.0) -> None:
        self.proc = subprocess.Popen([self.binary, "-c", str(self.conf)], stdout=subprocess.DEVNULL,
                                     stderr=subprocess.DEVNULL)
        end = time.monotonic() + timeout_s
        while time.monotonic() < end:
            if self.proc.poll() is not None:
                raise RuntimeError(f"mosquitto exited with {self.proc.returncode}; see {self.dir}/mosquitto.log")
            try:
                with socket.create_connection(("127.0.0.1", self.port), timeout=0.2):
                    self.events.append((time.monotonic(), "start"))
                    return
            except OSError:
                time.sleep(0.05)
        raise TimeoutError(f"mosquitto did not accept connections on port {self.port}")

    def kill(self) -> None:
        """Abrupt failure: SIGKILL, no orderly shutdown, connections reset."""
        self._signal(signal.SIGKILL, "kill")

    def stop(self) -> None:
        """Orderly shutdown: SIGTERM (persistence saved)."""
        self._signal(signal.SIGTERM, "stop")

    def _signal(self, sig, what: str) -> None:
        if self.proc and self.proc.poll() is None:
            self.proc.send_signal(sig)
            self.proc.wait(timeout=10)
            self.events.append((time.monotonic(), what))

    def log(self) -> str:
        p = self.dir / "mosquitto.log"
        return p.read_text(errors="replace") if p.exists() else ""

    def __enter__(self):
        self.start()
        return self

    def __exit__(self, *exc):
        self.stop()
