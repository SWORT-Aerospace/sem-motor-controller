#!/usr/bin/env python3
"""Parameterised electrical calculations and sensitivity study - SYNTHETIC inputs.

    python3 tools/run_electrical_calcs.py

Writes docs/generated/electrical_calcs_synthetic.md and docs/figures/*.png.
Candidate MOSFET figures are SEARCH-SNIPPET values (manufacturer sites were
unreachable from this environment) and are labelled UNVERIFIED; the
operating points are synthetic. The purpose is to show which missing
measurements dominate component selection, not to select components.
"""
from __future__ import annotations

import dataclasses
import math
import pathlib
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from models.inverter import losses as L  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Values as reported by WebSearch snippets of TI/Infineon pages - UNVERIFIED.
# qgs2 and plateau voltages are NOT from any source: assumed for the method.
CANDIDATES = {
    "CSD19536KTT (D2PAK) [snippet]": L.MosfetParams(2.4e-3, 0.006, 118e-9, 17e-9, 10e-9, 335e-9, 100e-9, 0.8, 4.5, 1.2, 0.4, "UNVERIFIED"),
    "CSD19535KTT (D2PAK) [snippet]": L.MosfetParams(3.4e-3, 0.006, 75e-9, 11e-9, 8e-9, 210e-9, 80e-9, 0.8, 4.5, 1.2, 0.5, "UNVERIFIED"),
    "CSD19532Q5B (SON5x6) [snippet]": L.MosfetParams(4.9e-3, 0.006, 48e-9, 8.7e-9, 6e-9, 128e-9, 60e-9, 0.8, 4.5, 1.2, 0.8, "UNVERIFIED"),
    "BSC040N10NS5 (SuperSO8) [snippet]": L.MosfetParams(4.0e-3, 0.006, 58e-9, 12e-9, 7e-9, 75e-9, 50e-9, 0.8, 4.5, 1.0, 0.9, "UNVERIFIED"),
}
GATE = L.GateDriveParams(v_drive_V=10.0, i_source_A=0.3, i_sink_A=0.6, rg_external_ohm=5.0)  # synthetic settings

# SYNTHETIC operating points (from config/vehicle.synthetic.yaml + DP study)
V_BUS = 46.0
POINTS = {
    "cruise 6 m/s (light load)": dict(i_pk=2.0, m=0.62, pf=0.99, weight=0.25),
    "pulse/accel 6 m/s": dict(i_pk=20.0, m=0.75, pf=0.95, weight=0.15),
    "standing start peak": dict(i_pk=40.0, m=0.15, pf=0.6, weight=0.01),
    "coast, zero-current control": dict(i_pk=0.0, m=0.55, pf=1.0, weight=0.59),
}
L_PHASE = 150e-6
R_PHASE = 0.10


def ripple_copper_loss(v_bus, f_sw, l=L_PHASE, r=R_PHASE):
    """PWM ripple estimate: dI_pp <= V/(4 L f) at 50 % duty; RMS of a triangle = pp/(2 sqrt 3)."""
    dipp = v_bus / (4 * l * f_sw)
    return 3 * r * (dipp / (2 * math.sqrt(3))) ** 2


def weighted_loss(fet, f_sw=20e3, dt=200e-9, tj=60.0, n_par=1, include_coast_switching=True):
    tot = 0.0
    for name, p in POINTS.items():
        if p["i_pk"] == 0.0 and not include_coast_switching:
            continue
        op = L.InverterOperatingPoint(V_BUS, p["i_pk"], p["m"], p["pf"], f_sw, dt, tj, n_par)
        tot += p["weight"] * (L.inverter_losses(fet, GATE, op)["total_W"] + ripple_copper_loss(V_BUS, f_sw))
    return tot


def main() -> int:
    md = ["# Electrical calculations and sensitivity - SYNTHETIC", "",
          "> **SYNTHETIC operating points; MOSFET data are UNVERIFIED search-snippet values** (ti.com / "
          "infineon.com unreachable). `qgs2`, plateau voltage, Qrr and gate-drive settings are assumptions for the "
          "method. Nothing here selects or approves a component. Generated by `tools/run_electrical_calcs.py`.", ""]

    # 1. bus voltage design value
    vmax = L.max_bus_voltage(50.4, 0.25, 0.0)
    md += ["## 1. Design bus voltage", "",
           "V_design = V_max_charged x (1 + margin) + measured ringing. With the synthetic 12S pack (50.4 V) and "
           f"a 25 % placeholder margin: **{vmax:.1f} V** before ringing. The margin must be replaced by measured "
           "switching overshoot (double-pulse test) and any back-EMF/regen pumping. A device's absolute-maximum "
           "rating is not a continuous operating rating, and a 100 V-rated driver pin does not make a 100 V bus "
           "safe (the DRV8353 snippet data show VM 9-75 V operating, 80 V abs. max, VDRAIN 102 V abs. max - "
           "UNVERIFIED).", ""]

    # 2. loss breakdown per candidate per point
    md += ["## 2. Inverter loss by operating point (W, whole bridge, Tj solved iteratively, 20 kHz, 200 ns dead time)", "",
           "| candidate | " + " | ".join(POINTS) + " | run-weighted W |", "|---|" + "---|" * (len(POINTS) + 1)]
    for name, fet in CANDIDATES.items():
        cells = []
        for pname, p in POINTS.items():
            op = L.InverterOperatingPoint(V_BUS, p["i_pk"], p["m"], p["pf"], 20e3, 200e-9, 60.0)
            tj, r = L.solve_tj(fet, GATE, op, t_amb_C=50.0, rth_cs=0.5, rth_sa=8.0)
            cells.append(f"{r['total_W']:.2f} (Tj {tj:.0f})")
        md.append(f"| {name} | " + " | ".join(cells) + f" | {weighted_loss(fet):.2f} |")
    md += ["", "Time weights per operating point are synthetic (from the shape of the DP plan: mostly coasting, "
           "short pulses). **Finding:** at the light-load points that dominate an eco-marathon run, gate-charge, "
           "Coss and switching terms dominate and the lowest-RDS(on) device is not the most efficient; at the "
           "standing-start peak, conduction dominates. The ranking therefore depends on the real drive-cycle "
           "current distribution, which is unmeasured.", ""]

    # 3. paralleling
    fet = CANDIDATES["BSC040N10NS5 (SuperSO8) [snippet]"]
    md += ["## 3. Parallel devices per switch (BSC040N10NS5 snippet values)", "", "| devices per switch | run-weighted W | peak-point W |", "|---|---|---|"]
    for n in (1, 2, 3):
        op = L.InverterOperatingPoint(V_BUS, 40.0, 0.15, 0.6, 20e3, 200e-9, 80.0, n)
        md.append(f"| {n} | {weighted_loss(fet, n_par=n):.2f} | {L.inverter_losses(fet, GATE, op)['total_W']:.2f} |")
    md += ["", "More parallel devices lower peak-current conduction loss but raise gate-drive and Coss losses at "
           "light load; with these synthetic weights they do not improve run energy.", ""]

    # 4. switching frequency (H1)
    fs = np.array([5e3, 8e3, 10e3, 15e3, 20e3, 30e3, 40e3])
    tot = [weighted_loss(fet, f_sw=f) for f in fs]
    rip = [ripple_copper_loss(V_BUS, f) for f in fs]
    md += ["## 4. Switching frequency (hypothesis H1)", "",
           "| f_sw kHz | run-weighted inverter + ripple-copper W | ripple copper W |", "|---|---|---|"]
    for f, t, r in zip(fs, tot, rip):
        md.append(f"| {f/1e3:.0f} | {t:.2f} | {r:.2f} |")
    fopt = fs[int(np.argmin(tot))]
    md += ["", f"With L = {L_PHASE*1e6:.0f} uH (synthetic) the minimum is near **{fopt/1e3:.0f} kHz**. Ripple-induced "
           "iron loss is not modelled. The optimum moves with the real motor inductance and the light-load fraction - "
           "both unknown. Coasting with gates off removes the switching term entirely when back-EMF < Vbus.", ""]

    # 5. dead time
    md += ["## 5. Dead time (hypothesis H2)", "", "| dead time ns | run-weighted W |", "|---|---|"]
    for d in (50e-9, 100e-9, 200e-9, 400e-9):
        md.append(f"| {d*1e9:.0f} | {weighted_loss(fet, dt=d):.3f} |")
    md += ["", "Body-diode conduction grows linearly with dead time; the lower bound is set by measured switching "
           "transitions (shoot-through margin), not by this model. Voltage distortion is not modelled.", ""]

    # 6. shunt trade-off
    md += ["## 6. Phase-current shunt: dissipation vs resolution vs offset", "",
           "Amplifier gains 5/10/20/40 V/V and ~+/-3 mV input offset are DRV8353 CSA snippet values (UNVERIFIED). "
           "12-bit ADC, 3.3 V reference, 40 A peak.", "",
           "| shunt mOhm | gain | full scale A | LSB mA | shunt W @40 A pk | offset A @3 mV | offset vs 2 A cruise |",
           "|---|---|---|---|---|---|---|"]
    for r in (0.5e-3, 1e-3, 2e-3, 5e-3):
        for g in (5, 10, 20, 40):
            sh = L.shunt(r, 40.0, 0.7, 0.9, g, 3.3, 12, 3e-3)
            if sh["i_full_scale_A"] < 45 or sh["i_full_scale_A"] > 400:
                continue
            md.append(f"| {r*1e3:.1f} | {g} | {sh['i_full_scale_A']:.0f} | {sh['lsb_A']*1e3:.0f} | "
                      f"{sh['p_each_W']:.2f} | {sh['offset_A']:.2f} | {100*sh['offset_A']/2.0:.0f} % |")
    md += ["", "**Finding:** an uncalibrated 3 mV offset on a 1 mOhm shunt is a 3 A error, larger than the ~2 A "
           "cruise current. Per-board zero-current offset calibration (stored in the calibration blob, "
           "`inverter.current_offset_counts`), temperature-drift measurement and a separate high-resolution DC-bus "
           "energy monitor (INA228-class: ~1 uV offset snippet value) are required; phase-shunt data must not be used "
           "for energy accounting.", ""]

    # 7. DC link
    i_rms = 40.0 / math.sqrt(2)
    ms = np.linspace(0.05, 1.15, 23)
    icap = [L.dc_link_ripple_rms(i_rms, m, 0.9) for m in ms]
    worst = max(icap)
    md += ["## 7. DC-link capacitor ripple and precharge", "",
           f"Ripple RMS (Kolar-Round form, verified numerically in tests/simulation/test_models.py) at 40 A peak "
           f"phase current: worst case **{worst:.1f} A rms** at M ~ {ms[int(np.argmax(icap))]:.2f}. Continuous ripple "
           "rating should use the real drive-cycle RMS (unknown); peak events are short.", ""]
    for c_uF, r_pre in ((470, 47), (1000, 47), (2200, 22)):
        pc = L.precharge(c_uF * 1e-6, 50.4, r_pre)
        dv = L.bus_voltage_ripple_pp(40.0, 20e3, c_uF * 1e-6)
        md.append(f"- C = {c_uF} uF, R_pre = {r_pre} Ohm: tau {pc['tau_s']*1e3:.0f} ms, 95 % in "
                  f"{pc['t_to_fraction_s']*1e3:.0f} ms, resistor pulse energy {pc['resistor_energy_J']:.2f} J, initial "
                  f"peak {pc['peak_power_W']:.0f} W; switching ripple bound {dv:.2f} V pp at 40 A.")
    md += ["", "Under the (unverified) SEM rule that the e-stop physically isolates the battery with normally-open "
           "contacts, the controller sees a hard connect on every enable: precharge sizing and contactor/relay "
           "inrush rating are mandatory review items. Discharge of the DC link after isolation must be provided "
           "(bleeder or active) and its time constant documented.", ""]

    # 8. thermal / conductors / fuse / aux
    tj, r = L.solve_tj(fet, GATE, L.InverterOperatingPoint(V_BUS, 40.0, 0.15, 0.6, 20e3, 200e-9, 80.0),
                       t_amb_C=50.0, rth_cs=0.5, rth_sa=4.0)
    md += ["## 8. Thermal, conductors, fuse, auxiliary energy", "",
           f"- Hottest device at standing-start peak (continuous assumption), 50 degC enclosure, Rth_cs 0.5 + Rth_sa 4 K/W: "
           f"**Tj {tj:.0f} degC**. Real peaks are short: transient thermal impedance must be used with measured profiles.",
           f"- Battery cable 2 x 1 m, 4 mm2, at 15 A rms: {L.conductor_loss(15.0, 1.0, 4.0):.2f} W; at the 2 A cruise "
           f"current {L.conductor_loss(2.0, 1.0, 4.0)*1e3:.1f} mW.",
           f"- Fuse example (rating 40 A, 4 mm2 ampacity assumed 32 A): {L.fuse_coordination(30, 60, 10, 40, 32, 2000, 1500)} "
           "- the example deliberately fails two checks: wire and breaking capacity must be chosen together with the battery "
           "short-circuit current (unknown).", ""]
    aux = L.aux_energy_per_run({"controller logic + gate driver": 0.8, "INA228 + CAN transceiver": 0.1,
                                "companion computer (Pi-class)": 4.0, "cellular modem (average)": 1.5,
                                "GNSS": 0.15}, 1000.0)
    md += ["- Auxiliary energy per 1000 s run (SYNTHETIC power figures): " +
           ", ".join(f"{k} {v/1e3:.2f} kJ" for k, v in aux.items() if k != "total_J") +
           f"; **total {aux['total_J']/1e3:.1f} kJ** versus ~40 kJ synthetic propulsion energy. If, as the "
           "(unverified) rules indicate, a battery-electric car has no accessory battery and the joulemeter measures "
           "everything after the battery, telemetry/compute power is a first-order efficiency term (hypothesis H6).", ""]

    # 9. sensitivity (tornado) for run-weighted inverter loss
    base_fet = fet
    base = weighted_loss(base_fet)
    sens = []
    def vary(label, lo_fet=None, hi_fet=None, **kw):
        lo = weighted_loss(lo_fet or base_fet, **{k: v[0] for k, v in kw.items()})
        hi = weighted_loss(hi_fet or base_fet, **{k: v[1] for k, v in kw.items()})
        sens.append((label, lo, hi))
    vary("RDS(on) x0.5 / x2", dataclasses.replace(base_fet, rds_on_25_ohm=base_fet.rds_on_25_ohm * 0.5),
         dataclasses.replace(base_fet, rds_on_25_ohm=base_fet.rds_on_25_ohm * 2))
    vary("Qg x0.5 / x2", dataclasses.replace(base_fet, qg_C=base_fet.qg_C * 0.5), dataclasses.replace(base_fet, qg_C=base_fet.qg_C * 2))
    vary("Qgd+Qgs2 x0.5 / x2", dataclasses.replace(base_fet, qgd_C=base_fet.qgd_C * 0.5, qgs2_C=base_fet.qgs2_C * 0.5),
         dataclasses.replace(base_fet, qgd_C=base_fet.qgd_C * 2, qgs2_C=base_fet.qgs2_C * 2))
    vary("Qoss x0.5 / x2", dataclasses.replace(base_fet, qoss_C=base_fet.qoss_C * 0.5), dataclasses.replace(base_fet, qoss_C=base_fet.qoss_C * 2))
    vary("f_sw 10 / 40 kHz", f_sw=(10e3, 40e3))
    vary("dead time 100 / 400 ns", dt=(100e-9, 400e-9))
    vary("Tj 40 / 120 degC", tj=(40.0, 120.0))
    saved = dict(POINTS)
    POINTS.update({k: dict(v, i_pk=v["i_pk"] * 0.5) for k, v in saved.items()})
    lo = weighted_loss(base_fet)
    POINTS.update({k: dict(v, i_pk=v["i_pk"] * 2.0) for k, v in saved.items()})
    hi = weighted_loss(base_fet)
    POINTS.update(saved)
    sens.append(("drive-cycle phase current x0.5 / x2 (UNMEASURED)", lo, hi))
    sens.sort(key=lambda s: abs(s[2] - s[1]), reverse=True)
    md += ["## 9. Sensitivity of run-weighted inverter loss (tornado)", "",
           f"Baseline {base:.2f} W (BSC040N10NS5 snippet values, synthetic weights).", "",
           "| input varied | low W | high W | swing W |", "|---|---|---|---|"]
    for lab, lo, hi in sens:
        md.append(f"| {lab} | {lo:.2f} | {hi:.2f} | {abs(hi-lo):.2f} |")
    md += ["", "### Which missing measurements dominate component selection", "",
           "| selection decision | dominated by (missing measurement) | why |", "|---|---|---|",
           "| MOSFET V_DS rating | max charged pack voltage; measured switching overshoot; back-EMF at max speed | sets V_design (section 1) |",
           "| MOSFET RDS(on) vs Qg trade | drive-cycle phase-current distribution (time at light load vs peak) | ranking flips between light load and peak (section 2) |",
           "| parallel count | peak phase current and its duration; thermal path | conduction vs gate/Coss trade (section 3) |",
           "| PWM frequency | motor phase inductance; light-load fraction | ripple copper vs switching (section 4) |",
           "| shunt value / CSA gain | peak phase current; amplifier offset & drift; cruise current | full scale vs offset error (section 6) |",
           "| DC-link C and ripple rating | drive-cycle RMS phase current; modulation index range; battery/cable inductance | section 7 |",
           "| precharge resistor | DC-link C; isolation-relay topology (rule-dependent) | pulse energy, inrush |",
           "| fuse / conductors | BMS limits; battery short-circuit current; harness length | section 8 |",
           "| heatsink / enclosure | loss profile over a run; enclosure ambient; airflow | section 8 |",
           ""]
    (ROOT / "docs" / "generated").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "generated" / "electrical_calcs_synthetic.md").write_text("\n".join(md))
    _plots(fs, tot, rip, sens, base, ms, icap)
    print("\n".join(md[:40]))
    return 0


def _plots(fs, tot, rip, sens, base, ms, icap):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    figdir = ROOT / "docs" / "figures"
    figdir.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.2))
    ax[0].plot(fs / 1e3, tot, "o-", label="inverter + ripple copper")
    ax[0].plot(fs / 1e3, rip, "s--", label="ripple copper only")
    ax[0].set_xlabel("PWM frequency [kHz]"); ax[0].set_ylabel("run-weighted loss [W]"); ax[0].legend()
    labels = [s[0] for s in sens][::-1]
    for i, (lab, lo, hi) in enumerate(sens[::-1]):
        ax[1].barh(i, hi - base, left=base, color="#c44")
        ax[1].barh(i, lo - base, left=base, color="#47a")
    ax[1].set_yticks(range(len(labels))); ax[1].set_yticklabels(labels, fontsize=7)
    ax[1].axvline(base, color="k", lw=0.8); ax[1].set_xlabel("run-weighted inverter loss [W]")
    ax[2].plot(ms, icap); ax[2].set_xlabel("modulation index M"); ax[2].set_ylabel("DC-link ripple RMS [A] @40 A pk")
    fig.suptitle("SYNTHETIC operating points / UNVERIFIED snippet MOSFET data - method demonstration only", color="#b00")
    fig.tight_layout()
    fig.savefig(figdir / "electrical_sensitivity_synthetic.png", dpi=110)
    plt.close(fig)


if __name__ == "__main__":
    sys.exit(main())
