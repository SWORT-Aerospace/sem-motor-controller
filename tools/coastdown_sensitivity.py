#!/usr/bin/env python3
"""How grade, wind and speed noise bias a coast-down fit (SYNTHETIC vehicle, known truth).

    python3 tools/coastdown_sensitivity.py           -> docs/generated/coastdown_sensitivity.md
    python3 tools/coastdown_sensitivity.py --check   (exit 1 if the committed file differs)

Uses the repository's own model and fit (models/vehicle/longitudinal.py:
simulate_coastdown, fit_coastdown). The vehicle is SYNTHETIC_VEHICLE (Crr 0.0025,
CdA 0.035 m^2, 100 kg, 0.3 N constant drag): every number below is a property
of the method on that synthetic vehicle, not a measurement. Each case
simulates coast-downs from 14 to 2 m/s with a condition the fit does not know
about (a small grade, a steady wind) and fits them as if the road were flat
and the air still; "both directions" fits the run each way and averages A and C.
"""
from __future__ import annotations

import argparse
import dataclasses
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from models.vehicle.longitudinal import SYNTHETIC_VEHICLE as V, fit_coastdown, simulate_coastdown  # noqa: E402

OUT = ROOT / "docs" / "generated" / "coastdown_sensitivity.md"
CONST_DRAG = V.drivetrain_drag_N


def fit_one(grade=0.0, wind=0.0, noise=0.005, seed=1):
    t, v, m_eff = simulate_coastdown(V, 14.0, 2.0, dt=0.2, grade=grade, wind=wind, noise_mps=noise,
                                     rng=np.random.default_rng(seed))
    return fit_coastdown(t, v, m_eff, V.mass_kg)


def both(grade=0.0, wind=0.0, noise=0.005):
    a, b = fit_one(grade, wind, noise, seed=1), fit_one(-grade, -wind, noise, seed=2)
    return dataclasses.replace(a, A_N=(a.A_N + b.A_N) / 2, C_N_s2_m2=(a.C_N_s2_m2 + b.C_N_s2_m2) / 2,
                               identifiable=a.identifiable and b.identifiable)


def cases():
    return [("flat, still air, speed noise 0.005 m/s", fit_one()),
            ("flat, still air, speed noise 0.05 m/s (NEO-M9N velocity figure)", fit_one(noise=0.05)),
            ("+0.1 % grade unmodelled, one direction", fit_one(grade=0.001)),
            ("+0.1 % grade unmodelled, both directions averaged", both(grade=0.001)),
            ("+0.5 % grade unmodelled, one direction", fit_one(grade=0.005)),
            ("1 m/s tailwind unmodelled, one direction", fit_one(wind=1.0)),
            ("1 m/s wind unmodelled, both directions averaged", both(wind=1.0))]


def report() -> str:
    crr0, cda0 = V.crr, V.cda_m2
    L = ["# Coast-down fit sensitivity (SYNTHETIC vehicle)", "",
         "Generated by `tools/coastdown_sensitivity.py` with the repository's model and fit "
         "(`models/vehicle/longitudinal.py`). True values: Crr " f"{crr0}, CdA {cda0} m^2, mass {V.mass_kg:.0f} kg, "
         f"constant drag {CONST_DRAG} N. Coast-downs from 14 to 2 m/s, sampled at 5 Hz. A property of the method on a "
         "synthetic vehicle, not a measurement.", "",
         "| Case | Crr fitted | Crr error | CdA fitted (m^2) | CdA error | A and C separately identifiable |",
         "|---|---|---|---|---|---|"]
    for name, f in cases():
        crr, cda = f.crr(V.mass_kg, CONST_DRAG), f.cda(V.rho_air)
        L.append(f"| {name} | {crr:.5f} | {100 * (crr - crr0) / crr0:+.1f} % | {cda:.4f} | "
                 f"{100 * (cda - cda0) / cda0:+.1f} % | {'yes' if f.identifiable else 'no'} |")
    L += ["", "## Reading", "",
          "* Grade is the dominant error. A 0.1 % slope (1 m in 1 km) adds m g sin(theta), close to 40 % of this "
          "vehicle's rolling resistance, and the fit books all of it as rolling resistance. Driving the same section "
          "in both directions and averaging removes a constant grade to first order.",
          "* A steady wind shifts the aerodynamic term; both directions also cancel most of it.",
          "* Speed noise matters through the numerical derivative. The fit reports when A and C are no longer "
          "separately identifiable instead of returning a confident split.",
          "* Requirements for the real coast-down: both directions on the same flat section, wind recorded, speed "
          "from the wheel sensor (GNSS as a cross-check), the vehicle's mass and rotating inertia, and the "
          "freewheel state. The inertia sets m_eff; this study uses the model's own value.", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = report()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is not current: run tools/coastdown_sensitivity.py")
            return 1
        print(f"{OUT.relative_to(ROOT)}: current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
