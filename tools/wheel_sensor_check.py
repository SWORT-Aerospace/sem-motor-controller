#!/usr/bin/env python3
"""Can a Hall switch see every wheel magnet pass? Sampled (DRV5032) vs continuous (DRV5023-Q1).

    python3 tools/wheel_sensor_check.py            -> docs/generated/wheel_sensor_check.md
    python3 tools/wheel_sensor_check.py --check    (exit 1 if the committed file differs)

A magnet passing the sensor holds the field above the operate point for a
window of arc length w (set by magnet size, air gap and the sensor threshold;
to be measured on the bench). At vehicle speed v, wheel circumference C, magnet
radius r_m (distance of the magnet from the axle) and N magnets per revolution:

    revolutions per second   n   = v / C
    magnet tangential speed  v_m = 2 pi r_m n
    field window             t_w = w / v_m
    gap between magnets      t_g = (2 pi r_m / N - w) / v_m
    pulse rate               f_p = N n

A sampled switch looks at the field once per period t_S and latches the result
(DRV5032 SLVSDC7F p. 14). With an unsynchronised sampling phase the chance of
seeing one pass is min(1, t_w / t_S); every pass is guaranteed only if
t_w >= t_S,max and t_g >= t_S,max (the release must be sampled too). A
continuous switch needs t_w above its output delay and f_p below its bandwidth.

Datasheet values used (read; docs/TELEMETRY_CANDIDATES.md):
  DRV5032 DU/FA/FC/FD/AJ/ZE: t_S 27 / 50 / 75 ms (min/typ/max); FB: 117 / 200 / 286 ms (SLVSDC7F p. 6)
  DRV5023-Q1: output delay 13 typ / 25 max us, bandwidth 20 kHz min (SLIS163G p. 6)
Vehicle values are NOT known: C, r_m, w and N below are a labelled grid, not the vehicle.
"""
from __future__ import annotations

import argparse
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "generated" / "wheel_sensor_check.md"

SAMPLED = {"DRV5032 20 Hz versions": (0.027, 0.050, 0.075), "DRV5032FB (5 Hz)": (0.117, 0.200, 0.286)}
CONT_DELAY_MAX_S = 25e-6          # DRV5023-Q1 output delay, max
CONT_BW_MIN_HZ = 20e3             # DRV5023-Q1 bandwidth, min

C_PLACEHOLDER = 1.50              # m; config/vehicle.synthetic.yaml (SYNTHETIC)
SPEEDS_KMH = (1, 5, 10, 20, 30, 40, 50)


def windows(v_mps: float, C: float, r_m: float, w: float, N: int) -> dict:
    n = v_mps / C
    v_m = 2 * math.pi * r_m * n
    return {"n": n, "v_m": v_m, "t_w": w / v_m, "t_g": (2 * math.pi * r_m / N - w) / v_m, "f_p": N * n}


def p_detect(t_w: float, t_s: float) -> float:
    return min(1.0, t_w / t_s)


def v_guaranteed_kmh(C: float, r_m: float, w: float, t_s_max: float) -> float:
    """Highest vehicle speed at which every pass is seen (t_w >= t_S,max), ignoring the gap condition."""
    return w * C / (2 * math.pi * r_m * t_s_max) * 3.6


def report() -> str:
    r_m, w, N = 0.10, 0.010, 4
    L = ["# Wheel-magnet detection: sampled vs continuous Hall switch", "",
         "Generated by `tools/wheel_sensor_check.py`. **The geometry is a labelled grid, not the vehicle:** the "
         f"wheel circumference {C_PLACEHOLDER} m is the synthetic configuration's placeholder; magnet radius, field "
         "window and magnet count are assumptions to be replaced by the vehicle's values and a bench measurement of "
         "the field window. Datasheet timing as read (`docs/TELEMETRY_CANDIDATES.md`).", "",
         f"## Reference case: C = {C_PLACEHOLDER} m, magnet at r_m = {r_m * 100:.0f} cm, field window w = "
         f"{w * 1000:.0f} mm, N = {N} magnets", "",
         "| v (km/h) | pulses/s | field window t_w | gap t_g | P(see a pass), DRV5032 20 Hz at t_S typ 50 ms / max 75 ms "
         "| P, DRV5032FB at 200 / 286 ms | continuous switch (DRV5023-Q1) |", "|---|---|---|---|---|---|---|"]
    for v in SPEEDS_KMH:
        d = windows(v / 3.6, C_PLACEHOLDER, r_m, w, N)
        p20 = [p_detect(d["t_w"], t) for t in (0.050, 0.075)]
        pfb = [p_detect(d["t_w"], t) for t in (0.200, 0.286)]
        cont = "sees every pass" if d["t_w"] > CONT_DELAY_MAX_S and d["f_p"] < CONT_BW_MIN_HZ else "NO"
        L.append(f"| {v} | {d['f_p']:.1f} | {d['t_w'] * 1000:.2f} ms | {d['t_g'] * 1000:.1f} ms | "
                 f"{p20[0] * 100:.1f} % / {p20[1] * 100:.1f} % | {pfb[0] * 100:.1f} % / {pfb[1] * 100:.1f} % | {cont} |")
    L += ["", "## Highest speed at which a sampled switch sees every pass (t_w >= t_S,max)", "",
          "| field window w | magnet radius r_m | DRV5032 20 Hz (t_S,max 75 ms) | DRV5032FB (t_S,max 286 ms) |",
          "|---|---|---|---|"]
    for w_ in (0.005, 0.010, 0.020, 0.050):
        for r in (0.05, 0.10, 0.20):
            L.append(f"| {w_ * 1000:.0f} mm | {r * 100:.0f} cm | {v_guaranteed_kmh(C_PLACEHOLDER, r, w_, 0.075):.2f} km/h | "
                     f"{v_guaranteed_kmh(C_PLACEHOLDER, r, w_, 0.286):.2f} km/h |")
    d10 = windows(10 / 3.6, C_PLACEHOLDER, r_m, w, N)
    p10 = [p_detect(d10["t_w"], t) for t in (0.050, 0.075)]
    grid = [v_guaranteed_kmh(C_PLACEHOLDER, r, w_, 0.075) for w_ in (0.005, 0.010, 0.020, 0.050)
            for r in (0.05, 0.10, 0.20)]
    L += ["", "## Result", "",
          "A DRV5032 (any variant in SLVSDC7F) sees a wheel magnet only by chance at vehicle speeds. In the reference "
          f"case it sees {p10[1] * 100:.0f} to {p10[0] * 100:.0f} % of passes at 10 km/h (t_S max to typ), and fewer at "
          f"higher speed. Across the grid, a 20 Hz version is certain to see every pass only below "
          f"{min(grid):.1f} to {max(grid):.1f} km/h. Counting pulses with it would under-read wheel speed by a "
          "speed-dependent, random factor, so it is **not suitable for wheel speed**. The datasheet lists "
          "\"Battery-critical position sensing\", tamper detection, case sensing and valve position among its "
          "applications (SLVSDC7F p. 1); none is a rotating-wheel count. A continuous Hall switch such as the "
          "DRV5023-Q1 responds in at most 25 us and sees every pass with margin at any speed in the grid. That part "
          "is a comparison read from its datasheet, not a selection: its supply current (2.7 mA typ), unipolar "
          "south-pole operation, open-drain output, mounting and the vehicle's maximum speed must be checked first.", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = report()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is not current: run tools/wheel_sensor_check.py")
            return 1
        print(f"{OUT.relative_to(ROOT)}: current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
