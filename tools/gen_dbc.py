#!/usr/bin/env python3
"""Generate a DBC description of the semmc protocol for another team's CAN tools.

    python3 tools/gen_dbc.py [--base 0x300] [-o protocol/generated/semmc_base0x300.dbc]
    python3 tools/gen_dbc.py --check     # the committed default DBC is current

Purpose: the telematics proposal (telematics_overview / telematics_data_flow
v0.1) logs and forwards whatever the vehicle CAN bus carries. Its parser
needs exact message definitions; a DBC is the common exchange format.

* Source of truth stays protocol/protocol.yaml. The DBC is generated, never
  edited, and is checked against the golden vectors with an independent DBC
  parser (cantools) in tests/integration/test_dbc.py.
* --base relocates the 64-identifier block exactly as the controller's
  calibration parameter supervision.can_id_base does (multiple of 0x40).
  The CRC data id stays the canonical protocol number, so a DBC user who wants
  to CHECK the CRC must use the canonical number (comment in the file).
* Byte 0 (CRC-8/SAE-J1850 with data id) and byte 1 (sequence) are described as
  plain signals; a DBC cannot express the CRC algorithm.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_protocol  # noqa: E402

DEFAULT_OUT = ROOT / "protocol" / "generated" / "semmc_base0x300.dbc"
NODES = {"controller": "SEMMC", "companion": "SUPERVISOR"}


def _num(x) -> str:
    return f"{x:.10g}"


def build(spec: dict, base: int) -> str:
    if base % 0x40 or not 0 <= base <= 0x7C0:
        raise ValueError("base must be a multiple of 0x40 in 0..0x7C0 (validator rule 40)")
    senders = sorted({m["sender"] for m in spec["messages"]})
    nodes = [NODES.get(s, s.upper()) for s in senders]
    L = ['VERSION "semmc %d.%d"' % (spec["protocol"]["major"], spec["protocol"]["minor"]), "", "NS_ :", "",
         "BS_:", "", "BU_: " + " ".join(nodes), ""]
    comments, values = [], []
    for m in spec["messages"]:
        cid = m["id"] - 0x300 + base
        tx = NODES.get(m["sender"], m["sender"].upper())
        rx = " ".join(n for n in nodes if n != tx) or "Vector__XXX"
        L.append(f"BO_ {cid} {m['name']}: 8 {tx}")
        L.append(f' SG_ crc8 : 0|8@1+ (1,0) [0|255] "" {rx}')
        L.append(f' SG_ seq : 8|8@1+ (1,0) [0|255] "" {rx}')
        for f in m["fields"]:
            sign = "-" if f.get("signed") else "+"
            if f["kind"] == "scaled":
                sc, off, lo, hi, unit = f["scale"], f["offset"], f["min"], f["max"], f.get("unit", "")
            else:
                lo_raw, hi_raw = gen_protocol.raw_limits(f)
                sc, off, lo, hi, unit = 1, 0, lo_raw, hi_raw, ""
            L.append(f' SG_ {f["name"]} : {f["start"]}|{f["width"]}@1{sign} ({_num(sc)},{_num(off)}) '
                     f'[{_num(lo)}|{_num(hi)}] "{unit}" {rx}')
            if f.get("description"):
                comments.append(f'CM_ SG_ {cid} {f["name"]} "{f["description"].replace(chr(34), chr(39))}";')
            if f.get("invalid") is not None:
                values.append(f'VAL_ {cid} {f["name"]} {f["invalid"]} "INVALID" ;')
        desc = m.get("description", "").replace('"', "'")
        comments.append(f'CM_ BO_ {cid} "{desc} Period {m.get("period_s", "-")} s'
                        f'{" + on change" if m.get("on_change") else ""}. CRC data id = (major << 11) | 0x{m["id"]:03X} '
                        f'(canonical number, not the bus id)";')
        L.append("")
    L.append(f'CM_ "Generated by tools/gen_dbc.py from protocol/protocol.yaml (spec hash {gen_protocol.spec_hash((ROOT / "protocol" / "protocol.yaml").read_text())}). '
             f'Block base 0x{base:03X} = controller calibration supervision.can_id_base. Do not edit.";')
    L += comments + values + [""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", type=lambda s: int(s, 0), default=0x300)
    ap.add_argument("-o", "--out", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    spec = gen_protocol.load_spec()
    text = build(spec, a.base)
    out = a.out or (DEFAULT_OUT if a.base == 0x300 else ROOT / "protocol" / "generated" / f"semmc_base0x{a.base:03X}.dbc")
    if a.check:
        ok = out.exists() and out.read_text() == text
        print(f"{out.relative_to(ROOT)}: {'current' if ok else 'STALE'}")
        return 0 if ok else 1
    out.write_text(text)
    print(f"wrote {out.relative_to(ROOT)} ({len(spec['messages'])} messages, base 0x{a.base:03X})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
