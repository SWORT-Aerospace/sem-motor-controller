#!/usr/bin/env python3
"""Repository scope: which suite each tracked file and each test belongs to (docs/scope.yaml).

    python3 tools/scope.py            # write docs/generated/scope.md
    python3 tools/scope.py --check    # fail if a tracked file has no suite, or the page is stale

Suites: telematics (the delivery), reference (reusable simulation and reference), controller (deferred
controller development). conftest.py uses `test_suite` to mark every collected test.
"""
from __future__ import annotations

import argparse
import collections
import pathlib
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "scope.yaml"
DOC = ROOT / "docs" / "generated" / "scope.md"


def load() -> dict:
    return yaml.safe_load(SRC.read_text())


def _longest(table: dict, path: str) -> str | None:
    best = None
    for prefix, suite in table.items():
        if path == prefix or (prefix.endswith("/") and path.startswith(prefix)):
            if best is None or len(prefix) > len(best[0]):
                best = (prefix, suite)
    return best[1] if best else None


def module_suite(path: str, data: dict | None = None) -> str | None:
    return _longest((data or load())["modules"], path)


def test_suite(nodeid: str, data: dict | None = None) -> str | None:
    """Suite of a pytest node id ('tests/x/test_y.py::test_z[param]'): an entry for the test, else the file's."""
    t = (data or load())["tests"]
    file, _, name = nodeid.partition("::")
    key = f"{file}::{name.split('[')[0]}" if name else None
    if key and key in t:
        return t[key]
    return _longest({k: v for k, v in t.items() if "::" not in k}, file)


def tracked() -> list[str]:
    return subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split()


def render(data: dict) -> tuple[str, list[str]]:
    files = tracked()
    missing = [f for f in files if module_suite(f, data) not in data["suites"]]
    by = collections.defaultdict(list)
    for f in files:
        by[module_suite(f, data)].append(f)
    top = collections.defaultdict(collections.Counter)
    for s, fs in by.items():
        for f in fs:
            parts = f.split("/")
            top[s]["/".join(parts[:2]) + ("/" if len(parts) > 2 else "")] += 1
    L = ["# Repository scope", "",
         "Generated by `tools/scope.py` from [`docs/scope.yaml`](../scope.yaml); do not edit. Every tracked file "
         "and every test belongs to one suite. The telematics suite is the delivery and must pass without building "
         "or fabricating the project's own motor controller (`python -m pytest -m \"telematics or reference\"`, the "
         "CI job `telematics`); the controller suite is deferred controller development, kept and tested in its own "
         "CI job.", "", "| Suite | Meaning | Tracked files |", "|---|---|---|"]
    for s, meaning in data["suites"].items():
        L.append(f"| `{s}` | {meaning} | {len(by.get(s, []))} |")
    for s in data["suites"]:
        L += ["", f"## {s}", "", "| Folder or file | Files |", "|---|---|"]
        L += [f"| `{k}` | {n} |" for k, n in sorted(top[s].items())]
    L.append("")
    return "\n".join(L), missing


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text, missing = render(load())
    if missing:
        print(f"tracked files without a suite in docs/scope.yaml: {missing}", file=sys.stderr)
        return 1
    if a.check:
        if not DOC.exists() or DOC.read_text() != text:
            print("docs/generated/scope.md is stale: run python3 tools/scope.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
