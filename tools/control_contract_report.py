#!/usr/bin/env python3
"""Before/after report for the control-contract correction (SYNTHETIC config).

    python3 tools/control_contract_report.py [--build build]

Runs build/semmc_contract_report on the synthetic calibration blob ("after"),
reads the frozen "before" run (docs/generated/control_contract_before.csv,
produced by the same harness against commit c0df363), and writes
docs/generated/control_contract_before_after.md plus the "after" CSV.
Exit status 1 if the "after" run violates the contract anywhere.
"""
from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GEN = ROOT / "docs" / "generated"

DESCR = {
    "A1_hard_ceiling_thermal_step": "Manual, 2.0 N*m; FET temperature step puts the thermal-derate ceiling at 1.0 N*m.",
    "A2_hard_ceiling_independent_of_slew": "As A1 with both down-slews set to 1 N*m/s: the clamp must not depend on slew settings.",
    "A3_battery_ceiling_rising_speed": "Manual, full throttle; speed rises 150->449 rad/s, then a 1000 rad/s estimate step.",
    "A4_envelope_torque_reduction": "ECO at 2.0 N*m; supervisor torque envelope drops to 0.5 N*m.",
    "A5_envelope_power_speed_step": "ECO with a 150 W power envelope; speed estimate steps 60->120 rad/s (envelope halves).",
    "A6_brake_deadman_reengage": "ECO 1.5 N*m; brake; release (no new edge); new eco edge; dead-man released.",
    "B1_lower_limits_before_matching_request": "CAN: set 7 (2.0 N*m) in force at 1.8 N*m; set 8 (0.5 N*m) committed; requests keep referencing 7 for 60 ms.",
    "B2_delayed_request_old_limits_ref": "CAN: set 8 (0.5) in force; a delayed request (new seq) referencing set 7 (2.0) arrives, then a stream of them.",
    "B3_reordered_request_ignored": "CAN: a reordered request (old sequence number, 2.0 N*m) arrives during 0.8 N*m.",
    "B4_busoff_stale_reengage": "CAN: bus-off at 1.2 N*m; re-handshake with set 9 (0.6); driver edge; then the supervisor stops sending.",
}


def parse(path: pathlib.Path):
    rows, summ = [], {}
    for line in path.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        f = line.split(",")
        if f[0] == "R":
            rows.append(dict(scn=f[1], t=f[2], event=f[3], state=f[4], req=f[5], acc=f[6], iq=f[7], hard=f[8],
                             env=f[9], rhex=f[10], reasons=f[11]))
        elif f[0] == "S":
            summ[f[1]] = dict(updates=int(f[2]), hard_v=int(f[3]), hard_x=float(f[4]), env_v=int(f[5]),
                              env_x=float(f[6]), settle=float(f[7]))
    return rows, summ


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default=str(ROOT / "build"))
    a = ap.parse_args()
    exe = pathlib.Path(a.build) / "semmc_contract_report"
    blob = pathlib.Path(a.build) / "cal" / "synthetic.bin"
    out = subprocess.run([str(exe), str(blob)], check=True, capture_output=True, text=True).stdout
    after_csv = GEN / "control_contract_after.csv"
    after_csv.write_text("# 'after' run: semmc_contract_report on the current tree, synthetic config.\n" + out)
    b_rows, b_sum = parse(GEN / "control_contract_before.csv")
    a_rows, a_sum = parse(after_csv)

    import yaml
    cfg = yaml.safe_load((ROOT / "config" / "vehicle.synthetic.yaml").read_text())
    tmax = float(cfg["limits"]["max_motor_torque_Nm"])
    sfast = float(cfg["limits"]["torque_slew_down_fast_Nm_s"])
    tout = float(cfg["supervision"]["timeout_s"])
    L = ["# Control contract: before / after (SYNTHETIC)", "",
         "> **What is checked, and what is not.** These rows check **command-ceiling compliance** (the accepted "
         "torque command against the hard ceiling) and **supervisory envelope ramp compliance** (against the "
         f"permitted ramp: output above the envelope must fall at no less than slew_down_fast = {sfast:g} N*m/s, i.e. by "
         f"slew_down_fast x dt on every update, so the worst-case deadline is max_motor_torque / slew_down_fast = {tmax:g} / {sfast:g} = "
         f"{1e3*tmax/sfast:.0f} ms, which validator rule 38 bounds by supervision.timeout_s = {1e3*tout:.0f} ms; "
         "SYNTHETIC values). They do **not** show the physical phase-current response (current-loop tracking on a "
         "real motor) or the battery-input current; those need bench measurements (`hardware/bringup/`).", "",
         "> Host harness `firmware/platform/host/contract_report_main.c` on the synthetic configuration. "
         "Before = arbiter/core of commit `c0df363`; after = this tree. The hard ceiling and envelope columns "
         "are computed by an **independent oracle in the harness** from the contract (not read back from the "
         "arbiter). Every update is checked, not only the rows shown. Not hardware evidence. Generated by "
         "`tools/control_contract_report.py`.", "",
         "## Contract checks over every update", "",
         f"| scenario | updates | hard-ceiling (command) violations before -> after (max excess N*m) | envelope-ramp violations before -> after (max excess N*m; permitted ramp >= {sfast:g} N*m/s, deadline {1e3*tmax/sfast:.0f} ms) | envelope settle ms before -> after |",
         "|---|---|---|---|---|"]
    bad = False
    for k in a_sum:
        b, s = b_sum.get(k), a_sum[k]
        bad |= s["hard_v"] > 0 or s["env_v"] > 0
        fmt = lambda v: "-" if v < 0 else f"{v:.0f}"  # noqa: E731
        L.append(f"| {k} | {s['updates']} | {b['hard_v']} ({b['hard_x']:.3f}) -> **{s['hard_v']}** ({s['hard_x']:.3f}) | "
                 f"{b['env_v']} ({b['env_x']:.3f}) -> **{s['env_v']}** ({s['env_x']:.3f}) | "
                 f"{fmt(b['settle'])} -> {fmt(s['settle'])} |")
    L += ["", "Envelope violation = output above the envelope and not falling by at least `slew_down_fast*dt` "
          "(the bounded ramp the contract permits). Settle = time from the first update with the output above "
          "the envelope until it is at or below it.", ""]
    for k in a_sum:
        L += [f"## {k}", "", DESCR.get(k, ""), "",
              "| t ms | event | state | requested | accepted before | accepted after | iq_ref A before | iq_ref A after "
              "| hard ceiling (after) | envelope (after) | reasons before | reasons after |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        br = [r for r in b_rows if r["scn"] == k]
        ar = [r for r in a_rows if r["scn"] == k]
        for i, r in enumerate(ar):
            o = br[i] if i < len(br) and br[i]["event"] == r["event"] else None
            L.append(f"| {r['t']} | {r['event']} | {r['state']} | {r['req']} | {o['acc'] if o else 'n/a'} | "
                     f"**{r['acc']}** | {o['iq'] if o else 'n/a'} | {r['iq']} | {r['hard']} | {r['env']} | "
                     f"`{o['reasons'] if o else 'n/a'}` | `{r['reasons']}` |")
        L.append("")
    (GEN / "control_contract_before_after.md").write_text("\n".join(L))
    print("contract violations in 'after' run:", "YES" if bad else "none")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
