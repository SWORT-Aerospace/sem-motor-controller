#!/usr/bin/env python3
"""The claims register: every claim's label and evidence, checked; and a scan of the docs for overclaiming.

    python3 tools/claims.py            # writes docs/CLAIMS.md
    python3 tools/claims.py --check    # exit 1 on a failed check or a stale page

Checks on docs/claims.yaml:
  * the label is one of SIMULATED, HOST-TESTED, BENCH-TESTED, HIL-TESTED, VEHICLE-TESTED;
  * every test named exists (`def <name>` in that file) and every file named exists;
  * a BENCH-TESTED, HIL-TESTED or VEHICLE-TESTED claim cites at least one record file under
    research/vehicle_validation/records/ or telematics/bench/results/ whose "Data class" row names that class;
  * no statement says "validated", "proven", "vehicle-ready" or "race-ready".
And on the current Markdown of the telematics delivery (docs/scope.yaml suite `telematics`, archives excluded): no
sentence claims that something is validated or proven, or vehicle- or race-ready, unless the sentence negates it.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tools import scope  # noqa: E402

SRC = ROOT / "docs" / "claims.yaml"
DOC = ROOT / "docs" / "CLAIMS.md"
PHYSICAL = {"BENCH-TESTED": "BENCH", "HIL-TESTED": "HIL", "VEHICLE-TESTED": "VEHICLE"}
RECORD_DIRS = ("research/vehicle_validation/records/", "telematics/bench/results/")
WORDS = re.compile(r"\b(validated|proven|vehicle-ready|race-ready)\b", re.I)
CLAIM = re.compile(r"\b(is|are|was|were|been|be)\s+(now\s+)?(fully\s+)?((bench|vehicle|hardware|field)-)?"
                   r"(validated|proven)\b|\b(vehicle|race)-ready\b", re.I)
NEGATION = re.compile(r"\b(not|no|never|nothing|none|without|until|unless|before|neither|nor|cannot)\b", re.I)


def load() -> dict:
    return yaml.safe_load(SRC.read_text())


def _test_exists(ref: str) -> bool:
    path, _, name = ref.partition("::")
    p = ROOT / path
    return p.exists() and (not name or re.search(rf"\bdef {re.escape(name)}\b", p.read_text()) is not None)


def check(d: dict) -> list[str]:
    err = []
    labels = d["labels"]
    if labels != ["SIMULATED", "HOST-TESTED", "BENCH-TESTED", "HIL-TESTED", "VEHICLE-TESTED"]:
        err.append("labels must be exactly SIMULATED, HOST-TESTED, BENCH-TESTED, HIL-TESTED, VEHICLE-TESTED")
    ids = [c["id"] for c in d["claims"]]
    if len(ids) != len(set(ids)):
        err.append("claim ids repeat")
    for c in d["claims"]:
        ev = c.get("evidence") or {}
        if c["label"] not in labels:
            err.append(f"{c['id']}: unknown label {c['label']}")
        if WORDS.search(c["statement"]):
            err.append(f"{c['id']}: the statement uses an overclaiming word")
        for t in ev.get("tests", ()):
            if not _test_exists(t):
                err.append(f"{c['id']}: test {t} not found")
        for f in ev.get("files", ()):
            if not (ROOT / f).exists():
                err.append(f"{c['id']}: file {f} not found")
        if not ev.get("tests") and not ev.get("records"):
            err.append(f"{c['id']}: no evidence")
        if c["label"] in PHYSICAL:
            recs = ev.get("records") or []
            if not recs:
                err.append(f"{c['id']}: {c['label']} needs a filled run sheet in {' or '.join(RECORD_DIRS)}")
            for r in recs:
                p = ROOT / r
                if not r.startswith(RECORD_DIRS) or not p.exists():
                    err.append(f"{c['id']}: record {r} not found under {' or '.join(RECORD_DIRS)}")
                elif not re.search(rf"\|\s*Data class\s*\|\s*{PHYSICAL[c['label']]}\b", p.read_text()):
                    err.append(f"{c['id']}: record {r} does not state data class {PHYSICAL[c['label']]}")
    err += [f"overclaim: {x}" for x in scan_docs()]
    return err


def scan_docs() -> list[str]:
    """Sentences in the telematics delivery's current Markdown that claim validation or readiness."""
    data, out = scope.load(), []
    for rel in scope.tracked():
        if not rel.endswith(".md") or scope.module_suite(rel, data) != "telematics" or "/archive/" in rel \
                or rel.startswith("docs/generated/") or rel == "docs/CLAIMS.md":
            continue
        text = (ROOT / rel).read_text(errors="replace")
        for n, line in enumerate(text.splitlines(), 1):
            for sentence in re.split(r"(?<=[.;:])\s+", line):
                if CLAIM.search(sentence) and not NEGATION.search(sentence):
                    out.append(f"{rel}:{n}: {sentence.strip()[:120]}")
    return out


def render(d: dict) -> str:
    L = ["# Claims and their evidence", "",
         "Generated by `python3 tools/claims.py` from [`claims.yaml`](claims.yaml); do not edit. Each claim has the "
         "strongest label its evidence supports. BENCH-TESTED, HIL-TESTED and VEHICLE-TESTED need a filled run sheet "
         "([`../research/vehicle_validation/RUN_SHEET.md`](../research/vehicle_validation/RUN_SHEET.md)); none exists "
         "yet, so no claim here is above HOST-TESTED.", ""]
    counts = {lab: sum(1 for c in d["claims"] if c["label"] == lab) for lab in d["labels"]}
    L += ["| Label | Claims |", "|---|---|"] + [f"| {k} | {v} |" for k, v in counts.items()] + [""]
    L += ["| Claim | Label | Statement | Evidence | Not shown |", "|---|---|---|---|---|"]
    for c in d["claims"]:
        ev = c.get("evidence") or {}
        refs = [f"`{t.split('::')[-1]}`" for t in ev.get("tests", ())] + [f"`{f}`" for f in ev.get("files", ())] + \
            [f"`{r}`" for r in ev.get("records", ())]
        L.append(f"| {c['id']} | {c['label']} | {c['statement']} | {', '.join(refs)} | {c.get('not_shown', '')} |")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    d = load()
    err = check(d)
    for e in err:
        print("claims: " + e)
    if err:
        return 1
    text = render(d)
    if a.check:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"stale: {DOC.relative_to(ROOT)} (run tools/claims.py)")
            return 1
        print(f"claims: {len(d['claims'])} claims checked, none above HOST-TESTED without a record; page current")
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
