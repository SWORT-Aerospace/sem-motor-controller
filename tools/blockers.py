#!/usr/bin/env python3
"""Render docs/BLOCKERS.md from docs/blockers.yaml.

    python3 tools/blockers.py           # write
    python3 tools/blockers.py --check   # fail if the document is out of date

The short list at the top groups the open blockers by the external input that closes them, in the order of
docs/blockers.yaml `groups` (most engineering work unlocked first). Team-internal items follow. Closed entries
keep the evidence that closed them.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/blockers.yaml"
DOC = ROOT / "docs/BLOCKERS.md"
FIELDS = [("missing", "Missing"), ("affects", "Affects"), ("why", "Why it matters"), ("done_now", "Done now"),
          ("input", "Input required"), ("closure", "Closure criterion"), ("evidence", "Evidence")]


def render(data: dict) -> str:
    bl = data["blockers"]
    open_ = sorted((b for b in bl if b["status"] == "open"), key=lambda b: -b["unlocks"])
    closed = [b for b in bl if b["status"] == "closed"]
    L = ["# Blocker-to-evidence register", "",
         "Generated by `tools/blockers.py` from `docs/blockers.yaml`; do not edit.", "",
         f"Battery: {data['battery_as_reported']}", "",
         "## What the team must send next", "",
         "Ordered by how much engineering work each answer unlocks.", "",
         "| # | Request | Closes |", "|---|---|---|"]
    for i, g in enumerate(data["groups"], 1):
        ids = [b for b in open_ if b.get("group") == g["id"]]
        L.append(f"| {i} | **{g['title']}**: {g['request']} | "
                 + ", ".join(f"[{b['id']}](#{b['id'].lower()})" for b in ids) + " |")
    team = [b for b in open_ if b.get("group") == "team"]
    L += ["", "Inside the team (no outside input): " + "; ".join(f"[{b['id']}](#{b['id'].lower()}) {b['title']}"
                                                            for b in team) + "."]
    L += ["", "## Open", ""]
    for b in open_:
        L += [f"### {b['id']}", "", f"**{b['title']}**", ""]
        L += [f"- **{name}:** {b[k]}" for k, name in FIELDS if b.get(k)]
        L.append("")
    L += ["## Closed in this revision", "", "| Id | Was | Closure | Evidence |", "|---|---|---|---|"]
    for b in closed:
        L.append(f"| {b['id']} | {b['title']} | {b['closure']} | {b['evidence']} |")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = yaml.safe_load(SRC.read_text())
    for b in data["blockers"]:
        missing = [k for k in ("id", "status", "title", "missing", "affects", "why", "done_now", "input", "closure",
                               "unlocks") if k not in b]
        if b.get("status") == "open" and b.get("group") not in {g["id"] for g in data["groups"]} | {"team"}:
            missing.append("group")
        if missing or b["status"] not in ("open", "closed") or (b["status"] == "closed" and not b.get("evidence")):
            print(f"{b.get('id')}: incomplete entry {missing}", file=sys.stderr)
            return 1
    text = render(data)
    if a.check:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"OUT OF DATE: {DOC.relative_to(ROOT)} (run tools/blockers.py)")
            return 1
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
