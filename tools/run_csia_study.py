#!/usr/bin/env python3
"""SYNTHETIC comparison: CSIA vehicle adapter vs simple checks vs fixed-threshold residuals.

    python3 tools/run_csia_study.py   -> docs/generated/csia_comparison_synthetic.md

Measures, per fault, the first correct attribution time and any wrong
attributions, and on the nominal run (normal events only) the number of
nuisance alarms. Synthetic sensors; the point is the method and the honest
reporting of ambiguity, not a claim about real sensor performance.
"""
from __future__ import annotations

import collections
import pathlib
import statistics
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from host.csia_adapter.adapter import VehicleCsiaAdapter  # noqa: E402
from host.csia_adapter.baselines import ResidualThreshold, SimpleChecks  # noqa: E402
from host.csia_adapter.synthetic import Fault, Scenario, generate, params  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
FAULTS = [Fault("wheel_l_dropout", 40, 60), Fault("rotor_stuck", 40, 70), Fault("gnss_offset", 30, 50, 1.5),
          Fault("imu_bias", 30, 50, 0.8), Fault("current_bias", 30, 50, 0.8), Fault("dc_gain", 40, 70, 1.4)]
TRUE_NODE = {"wheel_l_dropout": "wheel_l", "rotor_stuck": "rotor", "gnss_offset": "gnss", "imu_bias": "imu",
             "current_bias": "phase_current", "dc_gain": "dc_meter"}
B1_SIGNAL = {"wheel_l": "wheel_l", "rotor": "rotor", "gnss": "gnss", "imu": "imu_ax", "phase_current": "kcl",
             "dc_meter": "p_dc"}
B2_RESID = {"wheel_l": ("wheel_l_vs_r", "gnss_vs_wheel_l"), "rotor": ("rotor_vs_wheel_drive",),
            "gnss": ("gnss_vs_wheel_l", "gnss_vs_wheel_drive"), "imu": (), "phase_current": ("kcl",),
            "dc_meter": ("power",)}


def run_all(scn: Scenario):
    p = params()
    mons = {"csia": VehicleCsiaAdapter(p), "b1": SimpleChecks(p), "b2": ResidualThreshold(p)}
    data = generate(scn)
    k = 0
    out = {m: [] for m in mons}
    for j in range(1, int(scn.duration_s * 10)):
        t = j * 0.1
        while k < len(data) and data[k][0] <= t:
            _, name, s = data[k]
            for m in mons.values():
                m.ingest(name, s)
            k += 1
        for name, m in mons.items():
            out[name].append((t, m.tick(t)))
    return out


def main() -> int:
    nominal = run_all(Scenario())
    nuis = {
        "csia": sum(1 for _t, s in nominal["csia"] if s.suspects or s.ambiguous),
        "csia_suspects": sum(1 for _t, s in nominal["csia"] if s.suspects),
        "b1": sum(1 for _t, a in nominal["b1"] if a),
        "b2": sum(1 for _t, a in nominal["b2"] if a),
    }
    b2_kinds = collections.Counter(x for _t, a in nominal["b2"] for x in a)
    rows = []
    for f in FAULTS:
        r = run_all(Scenario(faults=(f,)))
        node = TRUE_NODE[f.kind]
        c_first = next((t for t, s in r["csia"] if t >= f.t0 and node in s.suspects), None)
        c_wrong = sorted({x for t, s in r["csia"] for x in s.suspects if x != node})
        c_amb = sum(1 for t, s in r["csia"] if f.t0 <= t < f.t1 and s.ambiguous and node not in s.suspects)
        b1_first = next((t for t, a in r["b1"] if t >= f.t0 and B1_SIGNAL[node] in a), None)
        b2_first = next((t for t, a in r["b2"] if t >= f.t0 and any(x in a for x in B2_RESID[node])), None)
        rows.append((f, node, c_first, c_wrong, c_amb, b1_first, b2_first))
    ticks = [s.elapsed_s for _t, s in nominal["csia"]]
    L = ["# CSIA vehicle adapter vs baselines - SYNTHETIC", "",
         "> Synthetic sensors and faults (`host/csia_adapter/synthetic.py`). Shadow mode only. Generated by "
         "`tools/run_csia_study.py`. Not evidence about real sensors.", "",
         "## Nominal run (normal events only)", "",
         "Normal events: standing-start traction slip, freewheel decoupling while coasting, three corners, "
         "+/-1 % grade, GNSS degradation 60-80 s, low-speed wheel-pulse quantisation, slow current-offset drift.", "",
         "| monitor | ticks with any alarm (of 1199) |", "|---|---|",
         f"| CSIA adapter (suspect or ambiguous) | {nuis['csia']} |",
         f"| B1 simple freshness/range checks | {nuis['b1']} |",
         f"| B2 fixed-threshold residuals (no regime gating) | {nuis['b2']} |", "",
         f"B2 nuisance alarms by residual: {dict(b2_kinds)}", "",
         "## Injected faults: first CORRECT attribution (s after injection)", "",
         "| fault | true node | CSIA first | CSIA wrong attributions | CSIA ambiguous ticks in window | B1 first | B2 first (cannot attribute) |",
         "|---|---|---|---|---|---|---|"]
    for f, node, c_first, c_wrong, c_amb, b1, b2 in rows:
        fmt = lambda x: "not detected" if x is None else f"{x - f.t0:.1f}"  # noqa: E731
        L.append(f"| {f.kind} ({f.t0:.0f}-{f.t1:.0f} s) | {node} | {fmt(c_first)} | {', '.join(c_wrong) or 'none'} | "
                 f"{c_amb} | {fmt(b1)} | {fmt(b2)} |")
    L += ["", "Notes:", "- Rotor-speed and power-balance relationships exist only while the motor drives through the "
          "freewheel; in this scenario the car coasts ~18 s between pulses, so detection of those faults waits for the "
          "next pulse (latency is regime-bound, reported, not hidden).",
          "- B2 'first' times are NOT meaningful where B2 was already alarming on the fault-free run (e.g. "
          "rotor_vs_wheel_drive alarms during freewheel coasting): its detection is confounded by its nuisance rate.",
          "- B2 raises an alarm on a residual but cannot say which sensor is wrong; B1 only sees stale/NaN/out-of-range "
          "values, so stuck-in-range, bias and gain faults pass it.",
          "- Ambiguous ticks are periods where the evidence supports disagreement only; the adapter reports them "
          "instead of guessing.", "",
          f"Adapter + CSIA TrustCore tick time on this host (x86-64, CPython, HOST BENCHMARK - not a target "
          f"measurement): mean {statistics.mean(ticks)*1e3:.2f} ms, max {max(ticks)*1e3:.2f} ms at 10 Hz.", ""]
    (ROOT / "docs" / "generated").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "generated" / "csia_comparison_synthetic.md").write_text("\n".join(L))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
