#!/usr/bin/env python3
"""Acceptance procedures: render the document, write record templates, check filled records.

    python3 tools/acceptance.py render [--check]            # docs/BENCH_ACCEPTANCE.md from the procedures
    python3 tools/acceptance.py template --stage S3 --board SN001 --out bench/records/SN001/S3.yaml
    python3 tools/acceptance.py check bench/records/SN001/S3.yaml [--config config/vehicle.<car>.yaml]

Procedures: hardware/acceptance/procedures.yaml. Blockers: docs/blockers.yaml.

A record passes a stage only when every step is `pass` or `recorded` (a measurement whose limit is still
pending), every measurement names its value, unit and instrument, every listed evidence file exists, and
the declared result agrees with the limit wherever the limit can be evaluated. A step that fails a `stop`
limit must be followed only by `not_run` steps. The checker never invents a limit: a `cfg:` limit whose
value is null in the configuration, or a limit marked pending, can only be `recorded`.
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROC = ROOT / "hardware/acceptance/procedures.yaml"
BLOCKERS = ROOT / "docs/blockers.yaml"
DOC = ROOT / "docs/BENCH_ACCEPTANCE.md"
RESULTS = ("pass", "fail", "recorded", "blocked", "not_run")


def load_procedures() -> dict:
    return yaml.safe_load(PROC.read_text())


def load_blockers() -> dict:
    if not BLOCKERS.exists():
        return {}
    return {b["id"]: b for b in yaml.safe_load(BLOCKERS.read_text())["blockers"]}


def cfg_value(cfg: dict | None, path: str):
    if cfg is None:
        return None
    node = cfg
    for k in path.split("."):
        if not isinstance(node, dict) or k not in node:
            return None
        node = node[k]
    return node


def resolve(v, cfg):
    """A limit bound: a number, or cfg:<path> read from the configuration (None if unavailable)."""
    if isinstance(v, (int, float)):
        return float(v)
    if isinstance(v, str) and v.startswith("cfg:"):
        x = cfg_value(cfg, v[4:])
        return float(x) if isinstance(x, (int, float)) and not isinstance(x, bool) else None
    return None


def describe_limit(lim: dict | None) -> str:
    if not lim:
        return "-"
    parts = []
    if "equals" in lim:
        parts.append(f"= {lim['equals']}")
    if "nominal" in lim:
        parts.append(f"nominal {lim['nominal']:g}")
    if "min" in lim:
        parts.append(f">= {lim['min'][4:] if str(lim['min']).startswith('cfg:') else format(lim['min'], 'g')}")
    if "max" in lim:
        parts.append(f"<= {lim['max'][4:] if str(lim['max']).startswith('cfg:') else format(lim['max'], 'g')}")
    text = ", ".join(parts)
    if "source" in lim:
        text += f" ({lim['source']})"
    if "pending" in lim:
        text += ("; " if text else "") + f"pending: {lim['pending']}"
    return text


# ----------------------------------------------------------------------------- render
def render(proc: dict, blockers: dict) -> str:
    L = ["# Bench and vehicle acceptance procedures", "",
         "Generated by `tools/acceptance.py render` from `hardware/acceptance/procedures.yaml`; do not edit.", "",
         proc["intro"].strip(), "",
         "Recording: `python3 tools/acceptance.py template --stage <S> --board <serial> --out "
         "bench/records/<serial>/<S>.yaml` writes a record to fill in; `python3 tools/acceptance.py check <record> "
         "--config <vehicle yaml>` checks it. `tools/bench_read.py` reads the controller's own values "
         "(`firmware/platform/stm32g4/FLASHING.md`). A limit marked pending is measured and recorded, not judged; "
         "it says what it waits for.", "", "## Rules for every stage", ""]
    L += [f"- {r}" for r in proc["rules"]]
    L += ["", "## Stages", "", "| Stage | Title | Energised | Can run now |", "|---|---|---|---|"]
    for st in proc["stages"]:
        blk = st.get("blocked_by")
        step_blk = sorted({s["blocked_by"] for s in st["steps"] if s.get("blocked_by")})
        now = "no: " + blk if blk else ("partly: " + ", ".join(step_blk) + " blocked" if step_blk else "yes, with a board")
        L.append(f"| [{st['id']}](#{st['id'].lower()}-{st['title'].lower().replace(' ', '-')}) | {st['title']} | "
                 f"{'yes' if st['energised'] else 'no'} | {now} |")
    for st in proc["stages"]:
        L += ["", f"## {st['id']} {st['title']}", "", st["purpose"], ""]
        if st.get("blocked_by"):
            b = blockers.get(st["blocked_by"], {})
            L += [f"**Blocked by {st['blocked_by']}**: {b.get('missing', 'see docs/BLOCKERS.md')}", ""]
        if st.get("equipment"):
            L += ["Equipment:", ""] + [f"- {e}" for e in st["equipment"]] + [""]
        if st.get("setup"):
            L += ["Setup:", ""] + [f"- {e}" for e in st["setup"]] + [""]
        L += ["| Step | Action | Expected | Limit | Stop |", "|---|---|---|---|---|"]
        for s in st["steps"]:
            lim = describe_limit(s.get("limit")) if s["kind"] == "measurement" else "observation"
            if s["kind"] == "measurement":
                lim = f"[{s['unit']}] {lim}"
            if s.get("blocked_by"):
                lim += f"; blocked by {s['blocked_by']}"
            stop = "stop" if s.get("stop") else ""
            if s.get("stop_note"):
                stop = s["stop_note"]
            L.append(f"| {s['id']} | {s['action']} | {s['expect']} | {lim} | {stop} |")
        L += ["", "Stop conditions:", ""] + [f"- {c}" for c in st["stop_conditions"]]
        L += ["", "Evidence to keep:", ""] + [f"- {e}" for e in st["evidence"]]
    return "\n".join(L) + "\n"


# ----------------------------------------------------------------------------- template
def template(proc: dict, stage_id: str, board: str) -> dict:
    st = next(s for s in proc["stages"] if s["id"] == stage_id)
    rec = {"schema": "semmc.acceptance.record.v1", "stage": stage_id, "board": board,
           "date": datetime.date.today().isoformat(), "operator": None, "witness": None,
           "firmware": {"image": None, "revision": None, "sha256": None},
           "config": {"file": None, "calibration_version": None},
           "equipment": [{"name": e, "model": None, "serial": None} for e in st.get("equipment", [])],
           "steps": {}}
    for s in st["steps"]:
        entry = {"result": "blocked" if s.get("blocked_by") else "not_run", "evidence": [], "notes": None}
        if s["kind"] == "measurement":
            entry.update({"value": None, "unit": s["unit"], "instrument": None})
        rec["steps"][s["id"]] = entry
    return rec


# ----------------------------------------------------------------------------- check
def check(proc: dict, blockers: dict, rec: dict, rec_dir: pathlib.Path, cfg: dict | None) -> tuple[list, dict]:
    errors = []
    st = next((s for s in proc["stages"] if s["id"] == rec.get("stage")), None)
    if st is None:
        return [f"unknown stage {rec.get('stage')!r}"], {}
    for k in ("board", "date", "operator"):
        if not rec.get(k):
            errors.append(f"header: {k} missing")
    if st["energised"]:
        if not rec.get("witness"):
            errors.append("header: witness missing (energised stage)")
        fw = rec.get("firmware") or {}
        if not fw.get("image") or not fw.get("sha256"):
            errors.append("header: firmware image and sha256 required")
        if any(not e.get("serial") for e in rec.get("equipment") or []):
            errors.append("header: every instrument needs a serial number")
    stage_blocked = st.get("blocked_by") and blockers.get(st["blocked_by"], {}).get("status") != "closed"
    counts = {r: 0 for r in RESULTS}
    stopped_at = None
    for s in st["steps"]:
        e = (rec.get("steps") or {}).get(s["id"])
        if e is None:
            errors.append(f"{s['id']}: missing")
            continue
        r = e.get("result")
        if r not in RESULTS:
            errors.append(f"{s['id']}: result {r!r} not one of {RESULTS}")
            continue
        counts[r] += 1
        blk = s.get("blocked_by") or (st.get("blocked_by") if stage_blocked else None)
        if blk and blockers.get(blk, {}).get("status") != "closed" and r not in ("blocked", "not_run"):
            errors.append(f"{s['id']}: {blk} is open, so the step can only be blocked")
        if stopped_at and r != "not_run":
            errors.append(f"{s['id']}: run after {stopped_at} failed a stop limit")
        for f in e.get("evidence") or []:
            if not (rec_dir / f).exists():
                errors.append(f"{s['id']}: evidence file {f} not found")
        if r in ("pass", "fail", "recorded") and s["kind"] == "measurement":
            if e.get("value") is None or not e.get("instrument"):
                errors.append(f"{s['id']}: value and instrument required")
                continue
            if e.get("unit") != s["unit"]:
                errors.append(f"{s['id']}: unit {e.get('unit')!r}, procedure says {s['unit']!r}")
            lim = s.get("limit") or {}
            verdict = None
            if "equals" in lim:
                verdict = str(e["value"]).strip().lower() == str(lim["equals"]).lower()
            else:
                lo, hi = resolve(lim.get("min"), cfg), resolve(lim.get("max"), cfg)
                wants = [b for b in ("min", "max") if b in lim]
                bounds_known = all(resolve(lim[b], cfg) is not None for b in wants)
                if wants and bounds_known and "pending" not in lim:
                    try:
                        x = float(e["value"])
                    except (TypeError, ValueError):
                        errors.append(f"{s['id']}: value {e['value']!r} is not a number")
                        continue
                    verdict = (lo is None or x >= lo) and (hi is None or x <= hi)
            if verdict is None and r != "recorded":
                errors.append(f"{s['id']}: the limit cannot be evaluated yet (pending or null in the configuration): "
                              f"result must be 'recorded'")
            if verdict is not None and r == "recorded":
                errors.append(f"{s['id']}: the limit can be evaluated: result must be pass or fail")
            if verdict is not None and r in ("pass", "fail") and verdict != (r == "pass"):
                errors.append(f"{s['id']}: declared {r}, but the value {e['value']} gives "
                              f"{'pass' if verdict else 'fail'} against {describe_limit(lim)}")
        if r == "fail" and s.get("stop"):
            stopped_at = s["id"]
    passed = not errors and counts["fail"] == counts["blocked"] == counts["not_run"] == 0
    return errors, {"stage": st["id"], "board": rec.get("board"), "counts": counts, "stage_passed": passed}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("render")
    r.add_argument("--check", action="store_true")
    t = sub.add_parser("template")
    t.add_argument("--stage", required=True)
    t.add_argument("--board", required=True)
    t.add_argument("--out", type=pathlib.Path, required=True)
    c = sub.add_parser("check")
    c.add_argument("record", type=pathlib.Path)
    c.add_argument("--config", type=pathlib.Path)
    c.add_argument("--json", type=pathlib.Path)
    a = ap.parse_args()
    proc, blockers = load_procedures(), load_blockers()
    if a.cmd == "render":
        text = render(proc, blockers)
        if a.check:
            if not DOC.exists() or DOC.read_text() != text:
                print(f"OUT OF DATE: {DOC.relative_to(ROOT)} (run tools/acceptance.py render)")
                return 1
            return 0
        DOC.write_text(text)
        print(f"wrote {DOC.relative_to(ROOT)}")
        return 0
    if a.cmd == "template":
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(yaml.safe_dump(template(proc, a.stage, a.board), sort_keys=False))
        print(f"wrote {a.out}")
        return 0
    rec = yaml.safe_load(a.record.read_text())
    cfg = yaml.safe_load(a.config.read_text()) if a.config else None
    errors, summary = check(proc, blockers, rec, a.record.parent, cfg)
    for e in errors:
        print("ERROR", e)
    print(json.dumps(summary))
    if a.json:
        a.json.write_text(json.dumps({"errors": errors, **summary}, indent=2) + "\n")
    return 0 if not errors else 1


if __name__ == "__main__":
    sys.exit(main())
